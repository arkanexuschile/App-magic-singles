export type AppLanguage = "es" | "en";

export function normalizeAppLanguage(value: string | null | undefined): AppLanguage | null {
  const normalized = value?.trim().toLowerCase() ?? "";

  if (!normalized) {
    return null;
  }

  if (normalized === "es" || normalized.startsWith("es-")) {
    return "es";
  }

  if (normalized === "en" || normalized.startsWith("en-")) {
    return "en";
  }

  return null;
}

export function detectLanguage(request: Request): AppLanguage {
  const url = new URL(request.url);
  const queryLang = normalizeAppLanguage(url.searchParams.get("lang"));
  if (queryLang) {
    return queryLang;
  }

  const header = request.headers.get("accept-language")?.toLowerCase() ?? "";
  if (header.includes("es")) {
    return "es";
  }
  return "en";
}

